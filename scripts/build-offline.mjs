#!/usr/bin/env node
// Offline fingerprints: hashes every file the site needs and writes the list,
// plus one build fingerprint, into the marked block of sw.js. The service
// worker uses it to know when a new version exists, which files changed and
// whether a download is intact.
//
//   node scripts/build-offline.mjs          rewrite the block in sw.js
//   node scripts/build-offline.mjs --check  exit 1 if sw.js is out of date
//
// Run it (or let the pre-commit hook run it) whenever a site file changes.

import { createHash } from "node:crypto";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SITE_ROOTS = ["index.html", "src"];
const SITE_EXTENSIONS = new Set(["html", "css", "js", "json", "webp", "png", "jpg", "svg", "ico", "woff2", "webmanifest"]);
const FILE_HASH_LENGTH = 16;
const BUILD_HASH_LENGTH = 12;
const BLOCK_START = "/* <precache> generated by `node scripts/build-offline.mjs` — do not edit by hand */";
const BLOCK_END = "/* </precache> */";
const WORKER_FILE = "sw.js";

const sha256 = (data) => createHash("sha256").update(data).digest("hex");

/** Short content fingerprint; the service worker computes the same value to verify downloads. */
export function fingerprint(bytes) {
  return sha256(bytes).slice(0, FILE_HASH_LENGTH);
}

const isSiteFile = (name) => !name.startsWith(".") && SITE_EXTENSIONS.has(name.split(".").pop().toLowerCase());

function walk(root, relative) {
  return readdirSync(join(root, relative), { withFileTypes: true }).flatMap((entry) => {
    if (entry.name.startsWith(".")) return [];
    const path = `${relative}/${entry.name}`;
    if (entry.isDirectory()) return walk(root, path);
    return entry.isFile() && isSiteFile(entry.name) ? [path] : [];
  });
}

/** Every file the app can request, as sorted site-relative paths. */
export function listSiteFiles(root) {
  const entries = new Map(readdirSync(root, { withFileTypes: true }).map((entry) => [entry.name, entry]));
  return SITE_ROOTS.flatMap((name) => {
    const entry = entries.get(name);
    if (!entry) return [];
    return entry.isDirectory() ? walk(root, name) : [name];
  }).sort();
}

/** { build, files: { path: fingerprint } } for the site under `root`. */
export function buildManifest(root) {
  const files = Object.fromEntries(
    listSiteFiles(root).map((path) => [path, fingerprint(readFileSync(join(root, path)))]),
  );
  const listing = Object.entries(files).map(([path, hash]) => `${path}:${hash}`).join("\n");
  return { build: sha256(listing).slice(0, BUILD_HASH_LENGTH), files };
}

export function renderBlock({ build, files }) {
  const lines = Object.entries(files).map(([path, hash]) => `  ${JSON.stringify(path)}: ${JSON.stringify(hash)},`);
  return [BLOCK_START, `const BUILD = ${JSON.stringify(build)};`, "const FILES = {", ...lines, "};", BLOCK_END].join("\n");
}

/** Returns `source` with its generated block replaced by `block`. */
export function applyBlock(source, block) {
  const start = source.indexOf(BLOCK_START);
  const end = source.indexOf(BLOCK_END);
  if (start < 0 || end < start) throw new Error(`${WORKER_FILE}: generated-block markers not found`);
  return source.slice(0, start) + block + source.slice(end + BLOCK_END.length);
}

function main(argv) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const workerPath = join(root, WORKER_FILE);
  const manifest = buildManifest(root);
  const current = readFileSync(workerPath, "utf8");
  const updated = applyBlock(current, renderBlock(manifest));
  const summary = `build ${manifest.build}, ${Object.keys(manifest.files).length} files`;

  if (updated === current) {
    console.log(`${WORKER_FILE} is up to date (${summary})`);
    return 0;
  }
  if (argv.includes("--check")) {
    console.error(`${WORKER_FILE} is out of date: site files changed. Run: node scripts/build-offline.mjs`);
    return 1;
  }
  writeFileSync(workerPath, updated);
  console.log(`${WORKER_FILE} updated (${summary})`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main(process.argv.slice(2));
  } catch (err) {
    console.error(err.message);
    process.exitCode = 1;
  }
}
