const CACHE_PREFIX = "cheatsheet-";
const CACHE = CACHE_PREFIX + BUILD;
const FILE_HASH_LENGTH = 16; // must match scripts/build-offline.mjs
const START_PAGE = "index.html";
const PARALLEL_DOWNLOADS = 6;

const urlOf = (path) => new URL(path, self.registration.scope).href;
const isListed = (path) => Object.prototype.hasOwnProperty.call(FILES, path);

async function fingerprint(response) {
  const digest = await crypto.subtle.digest("SHA-256", await response.arrayBuffer());
  const hex = Array.from(new Uint8Array(digest), (byte) => byte.toString(16).padStart(2, "0")).join("");
  return hex.slice(0, FILE_HASH_LENGTH);
}

/** A copy of `path` with the expected content from any of `stores`, or undefined. */
async function findSaved(path, stores) {
  for (const store of stores) {
    const saved = await store.match(urlOf(path));
    if (saved && (await fingerprint(saved.clone())) === FILES[path]) return saved;
  }
  return undefined;
}

/**
 * Gets `path` with exactly the expected content. First the normal way, which the
 * browser may answer from its own HTTP cache at no cost (the page has usually
 * just loaded the file). If that copy is not the right content, the server is
 * asked directly, so an outdated copy is never saved.
 */
async function download(path) {
  let problem = "";
  for (const cache of ["default", "no-store"]) {
    const response = await fetch(urlOf(path), { cache });
    if (response.ok && (await fingerprint(response.clone())) === FILES[path]) return response;
    problem = response.ok ? "fingerprint mismatch" : `HTTP ${response.status}`;
  }
  throw new Error(`${path}: ${problem}`);
}

async function inBatches(items, size, task) {
  for (let i = 0; i < items.length; i += size) {
    // Let the whole batch settle before failing, so files that did arrive stay
    // saved and the next attempt has less to download.
    const results = await Promise.allSettled(items.slice(i, i + size).map(task));
    const failed = results.find((result) => result.status === "rejected");
    if (failed) throw failed.reason;
  }
}

/** Fills this build's cache; rejects (leaving older builds untouched) if any file is wrong. */
async function saveBuild() {
  const names = (await caches.keys()).filter((name) => name.startsWith(CACHE_PREFIX));
  const target = await caches.open(CACHE);
  const stores = [target, ...(await Promise.all(names.filter((name) => name !== CACHE).map((name) => caches.open(name))))];

  await inBatches(Object.keys(FILES), PARALLEL_DOWNLOADS, async (path) => {
    if (await findSaved(path, [target])) return; // already here from an interrupted attempt
    const response = (await findSaved(path, stores)) || (await download(path));
    await target.put(urlOf(path), response);
  });
}

async function removeOtherBuilds() {
  const names = await caches.keys();
  await Promise.all(names.filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE).map((name) => caches.delete(name)));
}

/** Site-relative path of a request this worker owns, or null. */
function ownedPath(request) {
  if (request.method !== "GET") return null;
  const url = new URL(request.url);
  const scope = new URL(self.registration.scope);
  if (url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname)) return null;
  const path = url.pathname.slice(scope.pathname.length) || START_PAGE;
  return isListed(path) ? path : null;
}

async function serve(path, request) {
  const cache = await caches.open(CACHE);
  return (await cache.match(urlOf(path))) || fetch(request);
}

self.addEventListener("install", (event) => {
  // Take over as soon as the whole build is saved and verified.
  event.waitUntil(saveBuild().then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(removeOtherBuilds().then(() => self.clients.claim()));
});

self.addEventListener("message", (event) => {
  // A page asks which build it is being served (shown in Tools → Use offline).
  const port = event.ports && event.ports[0];
  if (port && event.data && event.data.type === "build") port.postMessage({ build: BUILD });
});

self.addEventListener("fetch", (event) => {
  const path = ownedPath(event.request);
  if (path !== null) event.respondWith(serve(path, event.request));
});
